# ==== FAST INVERSE (freq-only): real-data seeds + short local polish (+ tiny DE safety) ====
import numpy as np
import pandas as pd
from scipy.optimize import minimize, differential_evolution

# 1) Tighten bounds using percentiles (avoids wasting time at extremes)
def percentile_bounds(df, cols, lo=1.0, hi=99.0):
    q = df[cols].quantile([lo/100.0, hi/100.0])
    lo_vals = [float(q.loc[lo/100.0, c]) for c in cols]
    hi_vals = [float(q.loc[hi/100.0, c]) for c in cols]
    return list(zip(lo_vals, hi_vals))

# 2) Pick K real rows whose freq is closest to the target (good starting points)
def nearest_seeds_by_freq(df, cols, target_freq, k=8):
    idx_sorted = np.argsort(np.abs(df["freq_s11"].values - target_freq))
    return df.iloc[idx_sorted[:k]][cols].to_numpy(copy=True)

# 3) Objective (freq-only): minimize absolute gap to target
def make_objective_freq_only(model, target_freq):
    def f(x):
        y = model.predict(np.asarray(x, float).reshape(1, -1))[0]
        return abs(y - target_freq)
    return f

# 4) Fast inverse driver
def fast_inverse_freq_only(
    model,
    df_ref,
    design_cols,
    target_freq,
    k_seeds=8,                 # how many real seeds to start from
    bounds_pct=(1.0, 99.0),    # percentile bounds to shrink the box
    jitter_frac=0.01,          # small seed jitter as fraction of span
    local_maxiter=150,         # steps for local polish (per seed)
    good_enough_tol=0.03,      # GHz; early-stop if abs error <= tol
    use_de_fallback=True,      # tiny DE pass only if locals fail
    de_pop=8,                  # small population for DE fallback
    de_iters=12,               # few DE generations
    random_state=2025,
    top_k=3                    # how many final candidates to return
):
    rng = np.random.RandomState(random_state)

    # Bounds (percentiles, not raw min/max)
    bounds = percentile_bounds(df_ref, design_cols, lo=bounds_pct[0], hi=bounds_pct[1])
    lows  = np.array([b[0] for b in bounds]); highs = np.array([b[1] for b in bounds])
    span  = np.clip(highs - lows, 1e-9, None)

    # Seeds from real data near the target freq (fast & physically sane)
    seeds = nearest_seeds_by_freq(df_ref, design_cols, target_freq, k=k_seeds)
    # Jitter seeds a bit to avoid identical starts
    seeds = np.clip(seeds + rng.normal(scale=jitter_frac*span, size=seeds.shape), lows, highs)

    # Objective
    obj = make_objective_freq_only(model, target_freq)

    # ---- Local polish from each seed (quick) ----
    local_rows = []
    for x0 in seeds:
        res = minimize(
            obj, x0, method="L-BFGS-B", bounds=bounds,
            options={"maxiter": local_maxiter, "maxfun": local_maxiter, "ftol": 1e-6}
        )
        x_best = res.x if res.success else x0
        pred   = float(model.predict(np.asarray(x_best).reshape(1, -1)))
        row = {c: v for c, v in zip(design_cols, x_best)}
        row.update({
            "target_freq": target_freq,
            "predicted_freq": pred,
            "abs_error": abs(pred - target_freq),
            "solver": "local"
        })
        local_rows.append(row)

        # Early-stop if good enough
        if row["abs_error"] <= good_enough_tol:
            return pd.DataFrame([row])

    results = local_rows[:]

    # ---- Tiny DE fallback (only if locals not within tolerance) ----
    if use_de_fallback:
        # Build a small initial population around the best locals
        best_locals = sorted(local_rows, key=lambda r: r["abs_error"])[:max(3, de_pop)]
        init_pop = []
        for r in best_locals:
            x0 = np.array([r[c] for c in design_cols])
            for _ in range(2):  # two small perturbations each
                xj = np.clip(x0 + rng.normal(scale=0.05*span), lows, highs)
                init_pop.append(xj)
        # If population is short, add some randoms inside bounds
        need = de_pop * len(design_cols) - len(init_pop)
        if need > 0:
            init_pop.extend(lows + rng.rand(need, len(design_cols)) * span)
        init_pop = np.asarray(init_pop)

        # Avoid CPU oversubscription (if model already uses many cores)
        try:
            # If model is a Pipeline with a RandomForest inside
            model.named_steps["randomforestregressor"].set_params(n_jobs=1)
        except Exception:
            pass

        de_res = differential_evolution(
            obj, bounds,
            maxiter=de_iters, popsize=de_pop,
            init=init_pop, recombination=0.7, tol=1e-2,
            updating="deferred", workers=-1, polish=True, seed=random_state
        )
        x = de_res.x
        pred = float(model.predict(np.asarray(x).reshape(1, -1)))
        row = {c: v for c, v in zip(design_cols, x)}
        row.update({
            "target_freq": target_freq,
            "predicted_freq": pred,
            "abs_error": abs(pred - target_freq),
            "solver": "DE_fallback"
        })
        results.append(row)

        # Restore RF parallelism if we changed it
        try:
            model.named_steps["randomforestregressor"].set_params(n_jobs=-1)
        except Exception:
            pass

    # ---- Dedup (round to 3 decimals) + return top_k ----
    dedup = {}
    for r in results:
        key = tuple(np.round([r[c] for c in design_cols], 3))
        if key not in dedup or r["abs_error"] < dedup[key]["abs_error"]:
            dedup[key] = r
    out = pd.DataFrame(dedup.values()).sort_values("abs_error").head(top_k).reset_index(drop=True)
    return out

