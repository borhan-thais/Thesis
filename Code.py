# 4) ALPS-style evaluation wrapper

import time
# -----------------------------
RUNS_PER_TARGET = 30                           # repeat N runs per target
BUDGET_EVALS = 120                             # curve budget (evaluations); we pad if we stop early
N_TEST_TARGETS = 10                            # how many test targets to evaluate (picked evenly)
BAND = (2.0, 3.0)                             # GHz band you care about
TOL = 0.03                                     # GHz: Hit@τ threshold (≈1% band)
BOUNDS_PCT = (1.0, 99.0)                       # percentile bounds for search
K_SEEDS = 8                                    # seeds per run
LOCAL_MAXITER = 120                            # local steps per seed
USE_DE_FALLBACK = False                        # off for evaluation (compare separately if you want)
DE_POP = 8
DE_ITERS = 12
RANDOM_STATE = 2025
df_train = pd.DataFrame(X_train, columns=design_cols).assign(freq_s11=y_train)
