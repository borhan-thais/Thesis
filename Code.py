# Uniform random seeds inside percentile bounds
def _random_seeds_by_bounds(df_seedpool, design_cols, k=8, bounds_pct=(1.0, 99.0), rng=None):
    if rng is None:
        rng = np.random.RandomState(0)
    q = df_seedpool[design_cols].quantile([bounds_pct[0]/100.0, bounds_pct[1]/100.0])
    lows  = q.loc[bounds_pct[0]/100.0].to_numpy(float)
    highs = q.loc[bounds_pct[1]/100.0].to_numpy(float)
    return lows + rng.rand(k, len(design_cols)) * (highs - lows), lows, highs

def one_run_convergence_random(model, df_seedpool, design_cols, target_freq,
                               k_seeds=8, local_maxiter=150,
                               bounds_pct=(1.0, 99.0), random_state=0, budget=120,
                               tol=0.03):
    """Same as your one_run_convergence, but seeds are random within percentile bounds."""
    import time
    t0 = time.time()

    rng = np.random.RandomState(random_state)
    seeds, lows, highs = _random_seeds_by_bounds(df_seedpool, design_cols, k=k_seeds,
                                                 bounds_pct=bounds_pct, rng=rng)

    best_err = np.inf
    curve = []

    def obj_factory():
        def obj(x):
            nonlocal best_err
            pred = model.predict(np.asarray(x, float).reshape(1, -1))[0]
            err = abs(pred - target_freq)
            if err < best_err:
                best_err = err
            curve.append(best_err)  # log best-so-far after each eval
            return err
        return obj

    bounds = list(map(tuple, zip(lows, highs)))

    for s in range(seeds.shape[0]):
        obj = obj_factory()
        _ = minimize(
            obj, seeds[s], method="L-BFGS-B", bounds=bounds,
            options={"maxiter": local_maxiter, "maxfun": local_maxiter, "ftol": 1e-6}
        )
        if best_err <= tol:
            break

    runtime = time.time() - t0

    # pad curve to budget
    if len(curve) == 0:
        evals_to_tol = np.nan
        padded = np.full(budget, np.inf, float)
    else:
        arr = np.asarray(curve)
        evals_to_tol = int(np.argmax(arr <= tol) + 1) if (arr <= tol).any() else np.nan
        padded = np.array(curve + [curve[-1]] * max(0, budget - len(curve)), float)[:budget]

    def _rauc(c, B):
        if len(c) == 0:
            return np.inf
        c = np.array(c, float)
        if len(c) < B:
            c = np.concatenate([c, np.full(B - len(c), c[-1], float)])
        else:
            c = c[:B]
        return float(np.sum(c))

    return {
        "target_freq": float(target_freq),
        "best_abs_error": float(best_err),
        "hit@tau": bool(best_err <= tol),
        "evals_to_tau": evals_to_tol,
        "rAUC": float(_rauc(curve, budget)),
        "runtime_sec": float(runtime),
        "curve": padded.tolist()
    }

