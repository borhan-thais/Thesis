def rauc_of_curve(curve, budget):
    """Discrete area under best-so-far error curve up to 'budget' evaluations (pad with last)."""
    if len(curve) == 0:
        return np.inf
    c = np.array(curve, float)
    if len(c) < budget:
        c = np.concatenate([c, np.full(budget - len(c), c[-1], float)])
    else:
        c = c[:budget]
    return float(np.sum(c))

def one_run_convergence(model, df_seedpool, design_cols, target_freq,
                        k_seeds=8, local_maxiter=150,
                        bounds_pct=(1.0, 99.0), random_state=0, budget=BUDGET_EVALS,
                        tol=TOL):
    """
    One ALPS-style run:
      - seeds from train near target (jittered)
      - optimize each seed with L-BFGS-B, logging best-so-far |Δf| after EVERY model call
      - stop early if tol is reached; PAD curve to 'budget' for rAUC
    Returns: dict with best_err, best_pred, curve (padded), evals_to_tol, runtime
    """
    t0 = time.time()

    # Build bounds and seeds (percentile bounds from SEED POOL, not target set)
    q = df_seedpool[design_cols].quantile([bounds_pct[0]/100.0, bounds_pct[1]/100.0])
    lows  = q.loc[bounds_pct[0]/100.0].to_numpy(float)
    highs = q.loc[bounds_pct[1]/100.0].to_numpy(float)
    span  = np.clip(highs - lows, 1e-9, None)

    rng = np.random.RandomState(random_state)
    seeds = nearest_seeds_by_freq(df_seedpool, design_cols, target_freq, k=k_seeds)
    seeds = np.clip(seeds + rng.normal(scale=0.01*span, size=seeds.shape), lows, highs)

    best_err = np.inf
    best_pred = None
    curve = []

    def obj_factory():
        # closure that logs after each model call
        def obj(x):
            nonlocal best_err
            pred = model.predict(np.asarray(x, float).reshape(1, -1))[0]
            err = abs(pred - target_freq)
            if err < best_err:
                best_err = err
            curve.append(best_err)       # log best-so-far after each evaluation
            return err
        return obj

    # Run seeds serially; keep global best and a single curve (append per-eval logs)
    bounds = list(map(tuple, zip(lows, highs)))

    for s in range(seeds.shape[0]):
        obj = obj_factory()
        res = minimize(
            obj, seeds[s], method="L-BFGS-B", bounds=bounds,
            options={"maxiter": local_maxiter, "maxfun": local_maxiter, "ftol": 1e-6}
        )
        # Optional early stop when tol reached; we still PAD to budget for rAUC
        if best_err <= tol:
            break

    runtime = time.time() - t0

    # Final prediction at the current best (optional)
    # We don’t store the actual x* here; for evaluation we care about errors/curves.
    if len(curve) == 0:
        evals_to_tol = np.nan
    else:
        arr = np.asarray(curve)
        evals_to_tol = int(np.argmax(arr <= tol) + 1) if (arr <= tol).any() else np.nan

    rauc = rauc_of_curve(curve, budget)
    # pad curve to budget for consistent plotting/statistics
    padded_curve = np.array(curve + [curve[-1]] * max(0, budget - len(curve)), float)[:budget]

    # Also compute a single achieved pred for reporting (best_err = |pred - target|)
    # We re-query once at the last candidate used by obj; for eval, best_err is sufficient.

    return {
        "target_freq": float(target_freq),
        "best_abs_error": float(best_err),
        "hit@tau": bool(best_err <= tol),
        "evals_to_tau": evals_to_tol,
        "rAUC": float(rauc),
        "runtime_sec": float(runtime),
        "curve": padded_curve.tolist()
    }

def pick_test_targets_evenly(df_test, n=N_TEST_TARGETS):
    # Pick n targets evenly across the band by quantiles
    qs = np.linspace(0.05, 0.95, n)
    vals = df_test["freq_s11"].quantile(qs).values
    return [float(v) for v in vals]

def evaluate_inverse_alps_style(model, df_seedpool, df_targets_set, design_cols,
                                runs_per_target=RUNS_PER_TARGET, budget=BUDGET_EVALS,
                                tol=TOL, random_state=RANDOM_STATE):
    rng = np.random.RandomState(random_state)
    targets = pick_test_targets_evenly(df_targets_set, n=N_TEST_TARGETS)

    all_runs = []
    for tgt in targets:
        for run in range(runs_per_target):
            rs = int(rng.randint(0, 1_000_000))
            out = one_run_convergence(
                model, df_seedpool, design_cols, tgt,
                k_seeds=K_SEEDS, local_maxiter=LOCAL_MAXITER,
                bounds_pct=BOUNDS_PCT, random_state=rs,
                budget=budget, tol=tol
            )
